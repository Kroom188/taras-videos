CAP_Q = ["تعرفها؟", "جربتها؟", "وش رأيك؟", "مين يحتاجها؟", "احفظها 📌", "شاركها 🔁"]
PAL = [["#0a8f84", "#fbb01b", "#4f8f3e"]]

EMO = re.compile(r"\s*(\S+)$")


def build(start):
    pools = {k: list(v) for k, v in T.items()}
    seq = []
    k = 0
    while len(seq) < 90:
        topic = ORDER[k % len(ORDER)]
        if pools[topic]:
            seq.append((topic, pools[topic].pop(0)))
        k += 1
    d0 = datetime.date.fromisoformat(start)
    files = []
    for day in range(30):
        date = (d0 + datetime.timedelta(days=day)).isoformat()
        items = []
        for j in range(3):
            n = day * 3 + j
            topic, (h1, h2, big, fact, detail) = seq[n]
            emoji = EMO.search(h2).group(1)
            hook_plain = f"{h1} {h2}"
            tags = ["#وظائف", "#وظائف_السعودية"] + TAGS[topic] + ["#careertok", "#اكسبلور"]
            caption = f"{hook_plain} {CAP_Q[n % len(CAP_Q)]} " + " ".join(tags)
            items.append({
                "id": f"{j+1:02d}", "tag": f"{topic} | {n+1}", "palette": PAL[0],
                "hook": f"{h1}<br>{h2}", "emoji": emoji, "big": big,
                "fact": fact, "detail": detail, "cta": CTAS[n % len(CTAS)],
                "duration": 17, "caption": caption[:150] if len(caption) > 150 else caption,
                "title": h1 + " " + EMO.sub("", h2),
            })
        path = f"engine/content-{date}.json"
        json.dump(items, open(path, "w"), ensure_ascii=False, indent=1)
        files.append(path)
    return files


